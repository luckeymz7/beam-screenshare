export const langs = ['en', 'pt-br', 'es'] as const;
export type Lang = (typeof langs)[number];
export const defaultLang: Lang = 'en';

export const langMeta: Record<Lang, { label: string; short: string; locale: string }> = {
  en: { label: 'English', short: 'EN', locale: 'en-US' },
  'pt-br': { label: 'Português', short: 'PT', locale: 'pt-BR' },
  es: { label: 'Español', short: 'ES', locale: 'es-ES' },
};

export const isLang = (s: string | null | undefined): s is Lang => !!s && (langs as readonly string[]).includes(s);

export function pickLang(cookie: string | undefined, acceptLanguage: string | null): Lang {
  if (isLang(cookie)) return cookie;
  // "pt-BR,pt;q=0.9,en;q=0.8": the first language we have wins
  for (const part of (acceptLanguage ?? '').toLowerCase().split(',')) {
    const tag = part.split(';')[0].trim();
    if (tag.startsWith('pt')) return 'pt-br';
    if (tag.startsWith('es')) return 'es';
    if (tag.startsWith('en')) return 'en';
  }
  return defaultLang;
}

