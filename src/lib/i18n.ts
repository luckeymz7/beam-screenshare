export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  const strings = dict[lang] ?? en;
  return (key, vars) => {
    const s = strings[key] ?? en[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
  };
}

/** Translates an error code returned by the API, falling back to its English message. */
export function errorText(t: T, data: { code?: string; error?: string }, fallback: Key) {
  const key = `err.${data.code}` as Key;
  return key in en ? t(key) : (data.error ?? t(fallback));
}
